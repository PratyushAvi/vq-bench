// Pull the rendered article out of Quarto's page, for the app to render.
//
// Quarto emits a whole HTML document: its own <head>, Bootstrap, and a navbar.
// Dropped into the app as a page instead, all of that is redundant -- the app
// already has a head, a stylesheet and a bar -- and worse, Bootstrap's own
// `html { font-size: 17px }` rescales every rem in the app's design.
//
// So keep only what Quarto is actually needed for: the rendered article body
// and its table of contents. The app supplies the chrome around it, which is
// what makes the guide a page of the site rather than a document beside it.
import { readFile, writeFile, mkdir } from "node:fs/promises";

const rendered = await readFile(
  new URL(".rendered/index.html", import.meta.url),
  "utf8",
);

function section(html, pattern) {
  const match = html.match(pattern);
  return match ? match[1].trim() : "";
}

const body = section(rendered, /<main class="content"[^>]*>([\s\S]*?)<\/main>/);
if (!body) throw new Error("could not find Quarto's <main> -- did the template change?");

// Quarto puts its own "On this page" heading inside the nav; the app renders
// that label itself, so drop it rather than show it twice.
const toc = section(rendered, /<nav id="TOC"[^>]*>([\s\S]*?)<\/nav>/)
  .replace(/<h2[^>]*>[\s\S]*?<\/h2>/, "")
  .trim();

/**
 * Rewrite in-page anchors for the app's hash router.
 *
 * Quarto links a heading as `#why-quantize-at-all`. The app routes on the
 * hash, so following that would replace `#guide` and drop the reader back on
 * the landing page. Namespacing them under the view -- `#guide/<id>` -- keeps
 * both meanings in one hash, and App.tsx scrolls to the part after the slash.
 */
const VIEWS = new Set(["playground", "guide", ""]);

function namespaceAnchors(html) {
  // A link the prose writes to another view -- `[playground](#playground)` --
  // already names a route and is left alone; only heading ids are namespaced.
  return html.replace(/href="#([^"]+)"/g, (whole, id) =>
    VIEWS.has(id) ? whole : `href="#guide/${id}"`,
  );
}

// A TS module rather than a raw .html: Vite then type-checks and bundles it
// like any other source, and there is no runtime fetch to fail.
const out = `// Generated by docs/extract.mjs from docs/index.qmd -- do not edit.
//
// Re-run \`npm run docs\` after changing the guide's source.

export const GUIDE_HTML = ${JSON.stringify(namespaceAnchors(body))};

export const GUIDE_TOC = ${JSON.stringify(namespaceAnchors(toc))};
`;

await mkdir(new URL("../src/generated/", import.meta.url), { recursive: true });
await writeFile(new URL("../src/generated/guide.ts", import.meta.url), out);
console.log(`  guide extracted (${body.length} chars, ${toc ? "with" : "no"} toc)`);
